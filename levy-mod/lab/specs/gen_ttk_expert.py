#!/usr/bin/env python3
"""Generates the ttk_expert_*.yaml specs (hostile-levy / time-to-kill lab, see warbands-mod/docs/TTK_EXPERT.md). Weapon tables must match CombatHarness.HostileLab.cs."""
import pathlib
import yaml

W = {  # stage -> [(kind, class, weapon, ammo)]
    0: [("gun", "R", "Minishark", "Silver Bullet"), ("bow", "R", "Demon Bow", "Flaming Arrow"), ("magic", "M", "Ruby Staff", ""), ("melee", "E", "Blade of Grass", ""), ("sniper", "R", "Musket", "Silver Bullet")],
    1: [("gun", "R", "Phoenix Blaster", "Meteor Shot"), ("bow", "R", "Molten Fury", "Flaming Arrow"), ("magic", "M", "Flamelash", ""), ("melee", "E", "Light's Bane", ""), ("sniper", "R", "Musket", "Meteor Shot")],
    3: [("gun", "R", "Clockwork Assault Rifle", "Silver Bullet"), ("bow", "R", "Mythril Repeater", "Hellfire Arrow"), ("magic", "M", "Crystal Storm", ""), ("melee", "E", "Excalibur", ""), ("sniper", "R", "Musket", "High Velocity Bullet")],
    5: [("gun", "R", "Megashark", "Chlorophyte Bullet"), ("bow", "R", "Chlorophyte Shotbow", "Chlorophyte Arrow"), ("magic", "M", "Nettle Burst", ""), ("melee", "E", "Terra Blade", ""), ("sniper", "R", "Sniper Rifle", "High Velocity Bullet")],
}
E = {  # stage -> [(npc, flying)]
    0: [("Zombie", 0), ("Skeleton", 0), ("DemonEye", 1), ("GoblinArcher", 0)],
    1: [("FireImp", 1), ("Demon", 1), ("Hellbat", 1), ("Hornet", 1)],
    3: [("Pixie", 1), ("ChaosElemental", 0), ("Corruptor", 1), ("Gastropod", 1)],
    5: [("BlueArmoredBones", 0), ("Necromancer", 0), ("SkeletonSniper", 0), ("SkeletonCommando", 0)],
}
base = dict(mods="vanilla", arena="a3")


def tip(name, seeds, weapons, arms, warm=240, win=1800):
    return dict(name=name, seeds=seeds, **base, tipsy=dict(warm=warm, win=win, dist=[16], motion=["strafe"], size=["small"], arms=arms, weapons=weapons))


out = pathlib.Path(__file__).parent
hdr = "# generated by gen_ttk_expert.py; see warbands-mod/docs/TTK_EXPERT.md\n"


def dump(fn, d):
    (out / fn).write_text(hdr + yaml.safe_dump(d, sort_keys=False, width=200))


# Q1: hostile levies vs the strafing stage-kit stand-in
ws = []
for s, lst in W.items():
    for n in (1, 3):
        for kind, cls, w, a in lst:
            ws.append(dict(name=w, ammo=a, cls=cls, kind=kind, every=dict(hl=1, k="levy", s=s, n=n)))
w3 = [w for w in ws if w["every"]["n"] == 3]
dump("ttk_expert_levy.yaml", tip("ttk_expert_levy", 10, ws, {"base": {}}, win=1200))
dump("ttk_expert_levy_nif.yaml", tip("ttk_expert_levy_nif", 8, w3, {"nif": {"nif": 1}}, win=1200))
dump("ttk_expert_levy_cn.yaml", tip("ttk_expert_levy_cn", 8, [w for w in w3 if w["kind"] in ("gun", "sniper")], {"cn": {"pc": "Cross_Necklace"}}, win=1200))
# Q3: ordinary enemies against the same stand-in
we = []
for s, lst in E.items():
    for n in (1, 3):
        for npc, fly in lst:
            we.append(dict(name=npc, cls="R", kind="enemy", every=dict(hl=1, k="enemy", e=npc, s=s, n=n, fly=fly)))
dump("ttk_expert_enemy.yaml", tip("ttk_expert_enemy", 8, we, {"base": {}}, warm=120, win=1200))
# Q2 + PvP + calibration (one seed each: the lab loops trials internally)
wc = []
for s in W:
    wc.append(dict(name="npcdef", cls="R", every=dict(hl=1, k="npcdef", s=s)))
    wc.append(dict(name="pvp", cls="R", every=dict(hl=1, k="pvp", s=s)))
wc.append(dict(name="calib", cls="R", every=dict(hl=1, k="calib", s=0, m="static", win=1500)))
dump("ttk_expert_calc.yaml", tip("ttk_expert_calc", 1, wc, {"base": {}}))

# max-life player (Eve: 400 HP pre-hardmode with all Life Crystals, 500 with Life Fruit), base arm only, more seeds
MAXHP = {0: 400, 1: 400, 3: 500, 5: 500}
wm = []
for w in ws:
    e = dict(w["every"]); e["ph"] = MAXHP[e["s"]]
    wm.append(dict(w, every=e))
dump("ttk_expert_levy_maxhp.yaml", tip("ttk_expert_levy_maxhp", 8, wm, {"base": {}}, win=1200))
